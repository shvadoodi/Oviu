function getLocale() {
  const path = window.location.pathname.toLowerCase();
  if (path.includes("/fr-ca")) return "fr-ca";
  if (path.includes("/fa")) return "fa";
  return "en-ca";
}

function applyLocale(locale) {
  const data = translations[locale] || translations["en-ca"];
  document.documentElement.lang = locale;
  document.documentElement.dir = locale === "fa" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    if (data[key]) node.textContent = data[key];
  });

  document.querySelectorAll("[data-i18n-html]").forEach((node) => {
    const key = node.getAttribute("data-i18n-html");
    if (data[key]) node.innerHTML = data[key];
  });

  document.querySelectorAll("[data-locale]").forEach((link) => {
    link.toggleAttribute("aria-current", link.getAttribute("data-locale") === locale);
  });
}

applyLocale(getLocale());
